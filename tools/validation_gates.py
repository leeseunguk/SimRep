#!/usr/bin/env python3
"""Run the registered comparisons and generate/check docs/validation/GATES.md.

Records are produced at the computation, never scraped from assertions.
The explicit population makes an absent/renamed gate fail rather than vanish.
"""
import argparse
from pathlib import Path
import subprocess
import tempfile
import os
from exact_solutions import load_catalog, render as render_exact

ROOT = Path(__file__).resolve().parents[1]
SMOOTH = [f"mms-{equation}-{geometry}" for equation in ("laplace", "poisson")
          for geometry in ("2d", "3d", "cylindrical")]
EXPECTED = set(SMOOTH + [f"{name}-center" for name in SMOOTH] + [
    "mms-linear-dielectric",
    "mms-cut-sphere-potential", "mms-cut-sphere-field",
    "mms-cut-cylinder-potential", "mms-cut-cylinder-field",
    "mms-global-cubic-potential", "mms-global-cubic-field",
    "mms-boundary-aware-potential", "mms-boundary-aware-field",
    *[f"mms-cut-flight-{shape}-{metric}" for shape in ("sphere", "cylinder")
      for metric in ("potential-max", "field-max", "potential-rms", "field-rms")],
    "comparison-poisson-planar", "comparison-poisson-cylindrical",
    "comparison-dielectric-coax", "comparison-parallel-plate-tof",
])
CATALOG = load_catalog()
EXPECTED.update(gate for case in CATALOG["cases"] for gate in case["gates"])
RUNS = [
    ("simrep-solve", "mms", None),
    ("simrep-fly", "mms", None),
    ("simrep-fly", "surface_reconstruction", "exact_surface_band_reconstruction_converges"),
    ("simrep-solve", "poisson", "manufactured_planar_and_cylindrical_poisson"),
    ("simrep-solve", "dielectric", "coaxial_dielectric_sleeve_is_second_order"),
    ("simrep-fly", "accuracy", "parallel_plate_tof_and_birth_time"),
    ("simrep-fly", "exact_solutions", None),
]
for case in CATALOG["cases"]:
    for test in case["tests"]:
        package, target, name = (test[key] for key in ("package", "target", "name"))
        if (package, target, None) not in RUNS and (package, target, name) not in RUNS:
            RUNS.append((package, target, name))
HEADER = """# Computed validation gates

Generated by `python3 tools/validation_gates.py --write`; CI runs `--check`.
Only the default CI-fast ladders are registered. Each row is emitted by its
test at the computation. Values are rounded to four significant figures.
This table is code verification against analytic solutions, not experimental
validation or a hardware-GPU claim.

`E = S - D`; `u_val = sqrt(u_num^2 + u_input^2 + u_D^2)`.
PASS means `abs(E) <= u_val`; MISS means `abs(E) > u_val`; OPEN means the
numerical uncertainty was not estimated. A passing assertion is not a
numerical uncertainty. GCI estimates use a consistent safety-factor convention
here; they are not rigorous bounds or calibrated standard deviations.

Order rows report the two-refinement endpoint order; their band also gives
the minimum adjacent order. They remain OPEN because no uncertainty on the
measured order is estimated. A below-documented order is a finding, not a
relaxed acceptance threshold. Smooth centre-potential rows use the signed
error at the same physical centre on all three grids, with absolute Celik GCI.

| Gate | Reference | Metric | S +/- u_num | D | E | u_val | Band / finding | Verdict |
| --- | --- | --- | --- | --- | --- | --- | --- | --- |
"""


def render(directory):
    rows = {}
    for path in directory.glob("*.tsv"):
        fields = path.read_text().strip().split("\t")
        if len(fields) != 10 or fields[0] in rows:
            raise ValueError(f"invalid or duplicate record: {path}")
        rows[fields[0]] = fields
    if rows.keys() != EXPECTED:
        raise ValueError(f"gate population mismatch: missing={EXPECTED-rows.keys()}, "
                         f"extra={rows.keys()-EXPECTED}")
    return HEADER + "".join(
        f"| {name} | {ref} | {metric} | {s} +/- {u} | {d} | {e} | {uv} | {band} | {verdict} |\n"
        for name, ref, metric, s, u, d, e, uv, band, verdict in
        (rows[key] for key in sorted(rows)))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    # Allows the coding agent to create the generated artifact using
    # apply_patch; normal developer runs use --write.
    mode.add_argument("--print", action="store_true")
    args = parser.parse_args()
    if args.check:
        exact_document = ROOT / "docs/validation/EXACT_SOLUTIONS.md"
        if exact_document.read_text() != render_exact(CATALOG):
            raise SystemExit("EXACT_SOLUTIONS.md is stale; render tools/exact_solutions.py --print")
    with tempfile.TemporaryDirectory(prefix="simrep-gates-") as temporary:
        environment = dict(os.environ, SIMREP_GATE_DIR=temporary)
        for package, test, name in RUNS:
            command = ["cargo", "test", "--release", "-p", package, "--test", test]
            if name:
                command += [name, "--", "--exact", "--nocapture"]
            else:
                command += ["--", "--nocapture"]
            subprocess.run(command, cwd=ROOT, env=environment, check=True)
        text = render(Path(temporary))
    destination = ROOT / "docs/validation/GATES.md"
    if args.write:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text)
    elif args.check:
        if destination.read_text() != text:
            raise SystemExit("GATES.md is stale; run python3 tools/validation_gates.py --write")
        print(f"GATES.md current: {len(EXPECTED)} computed gates")
    else:
        print(text, end="")


if __name__ == "__main__":
    main()
